    public static Language language() { return language; }
    public static void setLanguage(Language value) { language = Objects.requireNonNull(value); }
    public static String text(String key, Object... arguments) { return text(language, key, arguments); }
    public static String text(Language selected, String key, Object... arguments) {
        String template = selected == Language.ENGLISH ? ENGLISH.getOrDefault(key, key) : key;
        if (arguments.length == 0) return template;
        Matcher matcher = PARAMETER.matcher(template);
        StringBuilder result = new StringBuilder();
        while (matcher.find()) {
            int index = Integer.parseInt(matcher.group(1));
            matcher.appendReplacement(result, Matcher.quoteReplacement(index < arguments.length ? String.valueOf(arguments[index]) : matcher.group()));
        }
        matcher.appendTail(result); return result.toString();
    }
    static Map<String, String> englishMessages() { return ENGLISH; }
